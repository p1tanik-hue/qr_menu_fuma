async function main() {
  console.log('✍️  Обновляю описания...');
  let updated = 0;
  let missing = 0;
  for (const [name, description] of Object.entries(DESCRIPTIONS)) {
    const res = await prisma.product.updateMany({
      where: { name },
      data: { description },
    });
    if (res.count > 0) {
      updated += res.count;
    } else {
      missing += 1;
      console.warn(`  ⚠ не найдено: «${name}»`);
    }
  }
  console.log(`✅ Обновлено описаний: ${updated}. Не найдено позиций: ${missing}.`);
}

main()
  .catch((e) => {
    console.error('❌ Ошибка:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
